const assert = require('node:assert/strict');
const {pxForCm,contain} = require('../lib/dtf-math.cjs');
assert.equal(pxForCm(2.54),300);
assert.equal(pxForCm(30),3543);
assert.equal(pxForCm(35),4134);
assert.throws(()=>pxForCm(0),RangeError);
assert.throws(()=>pxForCm(NaN),RangeError);
const p=contain(1000,500,600,600);
assert.equal(p.width,600);
assert.equal(p.height,300);
assert.equal(p.x,0);
assert.equal(p.y,150);
const portrait=contain(500,1000,600,600);
assert.equal(portrait.width,300);
assert.equal(portrait.height,600);
assert.equal(portrait.x,150);
assert.equal(portrait.y,0);
assert.throws(()=>contain(0,500,600,600),RangeError);
console.log('PASS: DTF dimensions and proportional fit without distortion');
