'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict');
const src=fs.readFileSync('gestion/compras-recepcion-manual.js','utf8');
const start=src.indexOf('  async function recepcionarCompraCompleta(');
const end=src.indexOf('\n  function injectButtons()',start);
assert(start>=0&&end>start,'No se encontró recepción manual');
const fn=src.slice(start,end);
assert.match(fn,/supabaseClient\.rpc\('receive_stock_batch'/,'La recepción debe pasar por RPC');
assert.doesNotMatch(fn,/\.from\('purchases'\)\s*\.update\(/,'La recepción no debe sobrescribir estado desde el cliente');
assert.match(fn,/if\(!pending\.length\)/,'Debe contemplar compra sin pendientes');
assert.match(fn,/Number\.isSafeInteger\(ordered\)/,'Debe validar cantidades pedidas');
assert.match(fn,/Number\.isSafeInteger\(received\)/,'Debe validar cantidades recibidas');
assert.match(fn,/repeatedItems\.length/,'Debe bloquear líneas ambiguas');
assert.match(fn,/unassigned\.length/,'Debe bloquear líneas sin prenda asociada');
assert.doesNotMatch(src,/ordered_quantity:Math\.max\(1,Math\.round\(/,'No debe redondear silenciosamente las cantidades recuperadas');
assert.match(src,/Number\.isSafeInteger\(x\.ordered_quantity\)/,'Debe validar cantidades recuperadas de factura');
assert.doesNotMatch(src,/ordered_quantity:Math\.max\(1,Math\.round\(/,'No se deben redondear silenciosamente cantidades de factura');
assert.match(src,/Number\.isSafeInteger\(x\.ordered_quantity\)/,'La recuperación debe validar cantidades enteras');
assert.match(fn,/receivingPurchases\.add/,'Debe bloquear envío concurrente');
assert.match(fn,/receivingPurchases\.delete/,'Debe liberar bloqueo en finally');
assert.match(fn,/PODRÍA haberse registrado/,'Debe avisar de resultado ambiguo');
assert.match(src,/invoiceItems\.has\(id\)/,'La recuperación de factura debe rechazar prendas duplicadas');
assert.match(src,/Number\.isSafeInteger\(x\.ordered_quantity\)/,'La recuperación debe rechazar cantidades fraccionarias');
assert.match(src,/ordered_quantity:Number\(row\.querySelector/,'La recuperación no debe redondear cantidades');
assert.match(src,/const qty=line\.quantity==null\?'':String\(line\.quantity\)/,'Las cantidades originales de factura no deben redondearse');
assert.match(src,/new Set\(resolvedIds\)\.size!==resolvedIds\.length/,'Las asociaciones resueltas deben comprobar duplicados');
console.log('PASS: purchase receipt has single atomic RPC status owner and client guards');
